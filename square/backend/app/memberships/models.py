from sqlalchemy import func

from app.extensions import db


class MembershipType(db.Model):
    """An admin-configurable kind of membership (Individual, Family, ...) with its own price.

    `name` is the primary key rather than a surrogate id — it's the same string every
    Membership row already stores in its `membership_type` column, so this table replaces a
    hardcoded Python set with a real, admin-editable one instead of requiring a data migration
    of every historical Membership row. Renaming isn't supported (name is treated as a stable
    identifier); retire a type via `is_active` and create a new one instead.
    """

    __tablename__ = "membership_types"

    name = db.Column(db.String(20), primary_key=True)
    # Whole NOK, not øre — membership fees are round numbers and this field never mixes with
    # Order/Payment money math (which stays in minor units, see app/payments).
    price = db.Column(db.Integer, nullable=False, default=0)
    # Fixed set (monthly/quarterly/yearly) — a billing cadence, not something an admin needs to
    # invent new values for, so it stays a hardcoded choice like Membership.status rather than
    # getting its own table.
    billing_frequency = db.Column(db.String(20), nullable=False, default="yearly")
    # When true, `price` is never shown to a member or the public — the type's card/label shows
    # "Contact us for pricing" instead. Not tied to any particular type by name (e.g. Lifetime);
    # any type can be switched into "contact for pricing" mode and back.
    contact_for_price = db.Column(db.Boolean, nullable=False, default=False)
    is_active = db.Column(db.Boolean, nullable=False, default=True)
    sort_order = db.Column(db.Integer, nullable=False, default=0)
    # Short blurb shown on the public /membership page and the membership drive; admin-editable.
    description = db.Column(db.String(300), nullable=True)
    created_at = db.Column(db.DateTime(timezone=True), nullable=False, server_default=func.now())
    updated_at = db.Column(
        db.DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    def __repr__(self) -> str:
        return f"<MembershipType {self.name!r}>"


class Membership(db.Model):
    """One membership period for a Member.

    A member can have multiple rows over time (one per renewal), so
    membership history is preserved rather than overwritten in place.
    """

    __tablename__ = "memberships"

    id = db.Column(db.Integer, primary_key=True)
    member_id = db.Column(db.Integer, db.ForeignKey("members.id"), nullable=False, index=True)
    membership_type = db.Column(
        db.String(20), db.ForeignKey("membership_types.name"), nullable=False
    )
    # Conventional values: pending, active, expired, cancelled, suspended (PRD §14).
    status = db.Column(db.String(20), nullable=False, default="pending")
    start_date = db.Column(db.Date, nullable=False)
    end_date = db.Column(db.Date)
    created_at = db.Column(db.DateTime(timezone=True), nullable=False, server_default=func.now())
    updated_at = db.Column(
        db.DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    def __repr__(self) -> str:
        return f"<Membership {self.membership_type} ({self.status})>"


class MembershipPeriod(db.Model):
    """One billing period for a Membership — granularity follows the MembershipType's
    billing_frequency (12 rows/year for monthly, 4 for quarterly, 1 for yearly). Generated by
    app.memberships.service.generate_periods_for_membership(), never constructed ad hoc
    elsewhere. amount is snapshotted in øre at generation time and never changes even if the
    MembershipType's price changes later.
    """

    __tablename__ = "membership_periods"

    id = db.Column(db.Integer, primary_key=True)
    membership_id = db.Column(db.Integer, db.ForeignKey("memberships.id"), nullable=False, index=True)
    period_start = db.Column(db.Date, nullable=False)
    period_end = db.Column(db.Date, nullable=False)
    # "January 2027" | "Q1 2027" | "2027" — precomputed so the frontend never needs
    # per-granularity date-formatting logic.
    label = db.Column(db.String(50), nullable=False)
    # øre — see the money-unit crossover note in app/payments/models.py.
    amount = db.Column(db.Integer, nullable=False)
    currency = db.Column(db.String(3), nullable=False, default="NOK")
    status = db.Column(db.String(20), nullable=False, default="unpaid")  # unpaid | paid
    paid_at = db.Column(db.DateTime(timezone=True), nullable=True)
    created_at = db.Column(db.DateTime(timezone=True), nullable=False, server_default=func.now())
    updated_at = db.Column(
        db.DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    __table_args__ = (db.UniqueConstraint("membership_id", "period_start"),)

    def __repr__(self) -> str:
        return f"<MembershipPeriod {self.label!r} ({self.status})>"


class MembershipTypeChange(db.Model):
    """History note that a Membership's type was changed (e.g. Individual -> Family). Written by
    app.memberships.service.resync_periods_after_type_change(); shown muted on the member's
    dashboard instead of leaving the old type's periods lying around as "unpaid".
    """

    __tablename__ = "membership_type_changes"

    id = db.Column(db.Integer, primary_key=True)
    membership_id = db.Column(db.Integer, db.ForeignKey("memberships.id"), nullable=False, index=True)
    from_type = db.Column(db.String(20), nullable=False)
    to_type = db.Column(db.String(20), nullable=False)
    changed_at = db.Column(db.DateTime(timezone=True), nullable=False, server_default=func.now())
